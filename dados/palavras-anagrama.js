// ─── Constrói o array de objetos { palavra, categoria } ───
// Deduplica por palavra (garantia extra) e normaliza tudo para MAIÚSCULAS.
function construir () {
  const vistas = new Set()
  const lista = []
  for (const linhaBruta of BRUTA.split('\n')) {
    const linha = linhaBruta.trim()
    if (!linha) continue
    const [palavraBruta, categoriaBruta] = linha.split('|')
    const palavra = String(palavraBruta || '').trim().toUpperCase()
    const categoria = String(categoriaBruta || '').trim().toLowerCase()
    if (!palavra || !categoria || vistas.has(palavra)) continue
    vistas.add(palavra)
    lista.push({ palavra, categoria })
  }
  return lista
}

const PALAVRAS = construir()

// Categorias únicas (ordenadas) — usada para validar `/anagrama <categoria>`
const CATEGORIAS = [...new Set(PALAVRAS.map(p => p.categoria))].sort()

// 🔤 Normaliza texto (minúsculas + sem acento) para comparar categorias
function normalizar (texto) {
  return String(texto || '')
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
}

// ─── 🎲 Sorteia uma palavra (opcionalmente filtrando por categoria) ───
// Retorna { palavra, categoria } ou null se não houver pool.
function sortearPalavra (categoria) {
  const pool = categoria
    ? PALAVRAS.filter(p => p.categoria === normalizar(categoria))
    : PALAVRAS
  if (pool.length === 0) return null
  return pool[Math.floor(Math.random() * pool.length)]
}

module.exports = { PALAVRAS, CATEGORIAS, sortearPalavra, normalizar }
